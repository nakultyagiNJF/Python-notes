#! Math:------> 

#* Python has a set of built-in math functions, including an extensive math module, that allows you to perform mathematical tasks on numbers. 

#? Built-in Math Function:--->>
a = min(10, 54, 2, 9, 0, 34, 8)
print(a)

b = max(10, 54, 2, 9, 0, 34, 8)
print(b)

c = abs(-45.6)
print(c)

d = pow(4, 4)
print(d)

#? Math Modules:--->>
import math 

x = math.sqrt(64)
print(x)

y = math.ceil(3.8)
print(y)

z = math.floor(3.8)
print(z)